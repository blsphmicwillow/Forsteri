#!/usr/bin/env bash
# forsteri-theme-apply -- render one theme codename into the user's session.
#
#   forsteri-theme-apply              use /etc/forsteri/theme (or ember)
#   forsteri-theme-apply monolith     pick a codename explicitly
#   forsteri-theme-apply --list       print the installed codenames
#
# Themes are data (desktop/themes/<codename>/theme.conf); this script is the
# only thing that writes them into GTK, KDE, GNOME and Hyprland settings. It is
# safe to re-run and skips anything the running desktop does not have.
set -uo pipefail

THEMES=${FORSTERI_THEMES:-/usr/share/forsteri/themes}
FALLBACK=ember

list_themes() {
  local dir
  for dir in "$THEMES"/*/; do
    [[ -f $dir/theme.conf ]] && basename "$dir"
  done
}

if [[ ${1:-} == "--list" ]]; then
  list_themes
  exit 0
fi

codename=${1:-}
if [[ -z $codename ]]; then
  codename=$(cat /etc/forsteri/theme 2>/dev/null || true)
fi
[[ -n $codename ]] || codename=$FALLBACK

conf="$THEMES/$codename/theme.conf"
if [[ ! -f $conf ]]; then
  echo "forsteri-theme-apply: no theme '$codename' in $THEMES" >&2
  echo "forsteri-theme-apply: available: $(list_themes | tr '\n' ' ')" >&2
  exit 1
fi

# The file is root-installed data with KEY=value lines; sourcing it keeps the
# quoted values (FONT="Inter 11") intact.
set -a
# shellcheck source=/dev/null
. "$conf"
set +a

for key in CODENAME NAME ACCENT BG FG BASE CARD BORDER RADIUS BUTTON_RADIUS \
  FONT MONO BUTTONS GNOME_ACCENT BLUR; do
  if [[ -z ${!key:-} ]]; then
    echo "forsteri-theme-apply: $conf is missing $key" >&2
    exit 1
  fi
done

if [[ $CODENAME != "$codename" ]]; then
  echo "forsteri-theme-apply: $conf says CODENAME=$CODENAME, directory is $codename" >&2
  exit 1
fi

rgb() { printf '%d,%d,%d' "0x${1:1:2}" "0x${3:2}" "0x${5:2}"; }
ACCENT_RGB=$(rgb "$ACCENT")
BG_RGB=$(rgb "$BG")
FG_RGB=$(rgb "$FG")
BASE_RGB=$(rgb "$BASE")
CARD_RGB=$(rgb "$CARD")
BORDER_RGB=$(rgb "$BORDER")

mkdir -p "$HOME/.config/gtk-3.0" "$HOME/.config/gtk-4.0" \
  "$HOME/.config/forsteri" "$HOME/.config/hypr" \
  "$HOME/.local/share/color-schemes"

# ---------------------------------------------------------------------------
# GTK
# ---------------------------------------------------------------------------

cat >"$HOME/.config/gtk-3.0/gtk.css" <<GTK3
/* Forsteri OS -- $NAME ($CODENAME) -- generated by forsteri-theme-apply */

@define-color theme_bg_color $BG;
@define-color theme_fg_color $FG;
@define-color theme_base_color $BASE;
@define-color theme_text_color $FG;
@define-color theme_selected_bg_color $ACCENT;
@define-color theme_selected_fg_color $BASE;
@define-color insensitive_fg_color #6d6d7a;
@define-color borders $BORDER;
@define-color accent_color $ACCENT;

window {
  border-radius: ${RADIUS}px;
}

headerbar,
.titlebar {
  min-height: 36px;
  border-radius: ${RADIUS}px ${RADIUS}px 0 0;
}

button {
  border-radius: ${BUTTON_RADIUS}px;
  padding: 4px 11px;
}

entry {
  border-radius: ${BUTTON_RADIUS}px;
  padding: 4px 8px;
}

menu,
popover {
  border-radius: ${RADIUS}px;
}

scrollbar slider {
  border-radius: 999px;
  background-color: alpha($FG, 0.25);
}
GTK3

cat >"$HOME/.config/gtk-4.0/gtk.css" <<GTK4
/* Forsteri OS -- $NAME ($CODENAME) -- generated by forsteri-theme-apply */

@define-color accent_color $ACCENT;
@define-color accent_bg_color $ACCENT;
@define-color accent_fg_color $BASE;
@define-color window_bg_color $BG;
@define-color window_fg_color $FG;
@define-color view_bg_color $BASE;
@define-color view_fg_color $FG;
@define-color headerbar_bg_color $BG;
@define-color headerbar_fg_color $FG;
@define-color card_bg_color $CARD;
@define-color card_fg_color $FG;
@define-color popover_bg_color $CARD;
@define-color popover_fg_color $FG;
@define-color borders $BORDER;
@define-color theme_bg_color $BG;
@define-color theme_fg_color $FG;
@define-color theme_selected_bg_color $ACCENT;
@define-color theme_selected_fg_color $BASE;

window,
window.background {
  border-radius: ${RADIUS}px;
}

headerbar {
  min-height: 38px;
  padding: 0 10px;
  border-radius: ${RADIUS}px ${RADIUS}px 0 0;
  box-shadow: none;
}

button {
  border-radius: ${BUTTON_RADIUS}px;
  padding: 4px 12px;
  box-shadow: none;
}

button.suggested-action {
  background: @accent_bg_color;
  color: @accent_fg_color;
}

entry,
spinbutton,
dropdown > button {
  border-radius: ${BUTTON_RADIUS}px;
  padding: 5px 9px;
  box-shadow: none;
}

popover,
popover.background,
menu {
  border-radius: ${RADIUS}px;
  border: 1px solid alpha($BORDER, 0.8);
}

scrollbar slider {
  min-width: 8px;
  min-height: 8px;
  border-radius: 999px;
  background: alpha($FG, 0.25);
}
GTK4

# ---------------------------------------------------------------------------
# KDE colour scheme (picked up from the user's data directory)
# ---------------------------------------------------------------------------

cat >"$HOME/.local/share/color-schemes/$NAME.colors" <<COLORS
[General]
ColorScheme=$NAME
Name=$NAME
shadeSortColumn=true

[Colors:Button]
BackgroundAlternate=$CARD_RGB
BackgroundNormal=$BG_RGB
DecorationFocus=$ACCENT_RGB
DecorationHover=$ACCENT_RGB
ForegroundActive=$ACCENT_RGB
ForegroundInactive=159,182,200
ForegroundLink=127,178,217
ForegroundNegative=224,108,90
ForegroundNeutral=$ACCENT_RGB
ForegroundNormal=$FG_RGB
ForegroundPositive=127,191,138
ForegroundVisited=155,140,200

[Colors:Selection]
BackgroundAlternate=$ACCENT_RGB
BackgroundNormal=$ACCENT_RGB
DecorationFocus=$ACCENT_RGB
DecorationHover=$ACCENT_RGB
ForegroundActive=$BASE_RGB
ForegroundInactive=40,40,30
ForegroundLink=31,60,80
ForegroundNegative=120,40,30
ForegroundNeutral=80,60,10
ForegroundNormal=$BASE_RGB
ForegroundPositive=20,60,30
ForegroundVisited=60,40,80

[Colors:Tooltip]
BackgroundAlternate=$BASE_RGB
BackgroundNormal=$BASE_RGB
DecorationFocus=$ACCENT_RGB
DecorationHover=$ACCENT_RGB
ForegroundActive=$ACCENT_RGB
ForegroundInactive=159,182,200
ForegroundLink=127,178,217
ForegroundNegative=224,108,90
ForegroundNeutral=$ACCENT_RGB
ForegroundNormal=$FG_RGB
ForegroundPositive=127,191,138
ForegroundVisited=155,140,200

[Colors:View]
BackgroundAlternate=$BASE_RGB
BackgroundNormal=$BASE_RGB
DecorationFocus=$ACCENT_RGB
DecorationHover=$ACCENT_RGB
ForegroundActive=$ACCENT_RGB
ForegroundInactive=159,182,200
ForegroundLink=127,178,217
ForegroundNegative=224,108,90
ForegroundNeutral=$ACCENT_RGB
ForegroundNormal=$FG_RGB
ForegroundPositive=127,191,138
ForegroundVisited=155,140,200

[Colors:Window]
BackgroundAlternate=$CARD_RGB
BackgroundNormal=$BG_RGB
DecorationFocus=$ACCENT_RGB
DecorationHover=$ACCENT_RGB
ForegroundActive=$ACCENT_RGB
ForegroundInactive=159,182,200
ForegroundLink=127,178,217
ForegroundNegative=224,108,90
ForegroundNeutral=$ACCENT_RGB
ForegroundNormal=$FG_RGB
ForegroundPositive=127,191,138
ForegroundVisited=155,140,200

[WM]
activeBackground=$BASE_RGB
activeForeground=$FG_RGB
inactiveBackground=$BG_RGB
inactiveForeground=159,182,200
COLORS

# ---------------------------------------------------------------------------
# Hyprland: variables the shipped hyprland.conf sources
# ---------------------------------------------------------------------------

cat >"$HOME/.config/hypr/theme-vars.conf" <<HYPR
# Generated by forsteri-theme-apply from $NAME ($CODENAME).
\$accent = rgba(${ACCENT:1}dd)
\$accent_soft = rgba(${ACCENT:1}33)
\$inactive = rgba(${BORDER:1}aa)
\$radius = $RADIUS
\$blur = $([[ $BLUR == yes ]] && echo true || echo false)
HYPR

# ---------------------------------------------------------------------------
# Desktop environment knobs
# ---------------------------------------------------------------------------

if command -v gsettings >/dev/null 2>&1; then
  gsettings set org.gnome.desktop.wm.preferences button-layout "$BUTTONS" 2>/dev/null || true
  gsettings set org.gnome.desktop.interface color-scheme 'prefer-dark' 2>/dev/null || true
  gsettings set org.gnome.desktop.interface accent-color "$GNOME_ACCENT" 2>/dev/null || true
  gsettings set org.gnome.desktop.interface font-name "$FONT" 2>/dev/null || true
  gsettings set org.gnome.desktop.interface monospace-font-name "$MONO" 2>/dev/null || true
  gsettings set org.gnome.desktop.interface cursor-size 24 2>/dev/null || true
fi

if command -v kwriteconfig6 >/dev/null 2>&1; then
  kwriteconfig6 --file kdeglobals --group General --key ColorScheme "$NAME" || true
  kwriteconfig6 --file kdeglobals --group General --key accentColor "$ACCENT" || true
fi

if [[ -n ${HYPRLAND_INSTANCE_SIGNATURE:-} ]] && command -v hyprctl >/dev/null 2>&1; then
  hyprctl reload >/dev/null 2>&1 || true
  hyprctl setcursor Adwaita 24 >/dev/null 2>&1 || true
fi

# Record the choice for the next login and for the installer's summary.
printf '%s\n' "$CODENAME" >"$HOME/.config/forsteri/theme"
printf '%s\n' "$NAME" >"$HOME/.config/forsteri/theme-name"

exit 0
